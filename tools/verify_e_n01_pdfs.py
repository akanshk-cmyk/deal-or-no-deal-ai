"""Verify actual pypdf extraction of the fixed E-N01 draft, not arbitrary uploads."""

from datetime import date
from decimal import Decimal
from importlib.metadata import distribution
from io import BytesIO
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from deal_or_no_deal_ai.context import InputError, fingerprint
from deal_or_no_deal_ai.documents import OriginalBlock, ReviewScope, SourceVersion, verify_evidence
from tools.prepare_e_n01 import PACK, artifacts, digest


OUTPUT = ROOT / "var/evaluations/e-n01-pdf-verification"


def nonblank_lines(text):
    """Comparison only; originals remain untouched and saved independently."""
    return [line.rstrip() for line in text.splitlines() if line.strip()]


def check_expected_bytes(actual, expected):
    if actual != expected:
        raise InputError("KNOWN_CORPUS_BYTES_MISMATCH")


def revenue_columns(layout):
    """Known-case layout diagnostic; not the application Extraction Agent.

    Horizontal positions are layout-character offsets, not PDF glyph boxes.
    Reject missing/overlapping/straddling assignments instead of first-column
    assumptions. Expected answers are checked outside this function.
    """
    lines = layout.splitlines()
    header_indexes = [i for i, line in enumerate(lines) if line.startswith("ANNUAL PROJECTION ")]
    if len(header_indexes) != 1:
        raise InputError("MISSING_OR_AMBIGUOUS_TABLE_ROW")
    header_index = header_indexes[0]
    table_lines = []
    for line in lines[header_index + 1:]:
        if not line.strip():
            break
        table_lines.append(line)
    rows = [line for line in table_lines if line.startswith("Revenue ")]
    if len(rows) != 1:
        raise InputError("MISSING_OR_AMBIGUOUS_TABLE_ROW")
    header_tokens = list(re.finditer(r"\S+", lines[header_index]))[2:]
    row_tokens = list(re.finditer(r"\S+", rows[0]))[1:]
    if len(header_tokens) != 2 or len(row_tokens) != 2:
        raise InputError("MISSING_OR_AMBIGUOUS_YEAR_COLUMNS")
    years = [token.group() for token in header_tokens]
    if len(set(years)) != 2 or any(not y.isascii() or not y.isdigit() or len(y) != 4 for y in years):
        raise InputError("INVALID_YEAR_HEADERS")
    for year in years:
        try:
            date(int(year), 1, 1)
        except ValueError as exc:
            raise InputError("INVALID_YEAR_HEADERS") from exc
    centers = [Decimal(t.start() + t.end()) / 2 for t in header_tokens]
    half_gap = (centers[1] - centers[0]) / 2
    boundaries = (centers[0] - half_gap, centers[0] + half_gap, centers[1] + half_gap)
    mapping, locations = {}, []
    for token in row_tokens:
        if not token.group().isascii() or not token.group().isdigit():
            raise InputError("UNSUPPORTED_REVENUE_CELL")
        matches = [i for i in range(2) if boundaries[i] <= token.start() and token.end() <= boundaries[i + 1]]
        if len(matches) != 1 or years[matches[0]] in mapping:
            raise InputError("AMBIGUOUS_OR_STRADDLING_YEAR_CELL")
        year = years[matches[0]]
        mapping[year] = token.group()
        locations.append(dict(year=year, header_start=header_tokens[matches[0]].start(),
                              header_end=header_tokens[matches[0]].end(),
                              cell_start=token.start(), cell_end=token.end()))
    return dict(values=mapping, locations=locations,
                coordinate_space="LAYOUT_LINE_CHARACTER_OFFSETS_NOT_PDF_BOXES")


def verify_pack():
    # Only these fixed writer-generated bytes are permitted at this entry point.
    expected = artifacts()
    actual = {name: (PACK / name).read_bytes() for name in expected}
    for name, content in expected.items():
        check_expected_bytes(actual[name], content)
    manifest = json.loads(actual["manifest.json"])
    case = json.loads(actual["case.json"])
    if (len(manifest["sources"]) > 3 or manifest["byte_count"] > 10000000
            or manifest["page_count"] > 10):
        raise InputError("PACKAGE_LIMIT")
    package = distribution("pypdf")
    if package.metadata.get("License-Expression") != "BSD-3-Clause":
        raise InputError("PARSER_LICENSE_PROFILE_MISMATCH")
    license_file = next(p for p in package.files if str(p).endswith("licenses/LICENSE"))
    from pypdf import PdfReader  # Explicit invocation only; no startup activation.

    sources = tuple(SourceVersion(s["source_id"], s["version"], s["content_digest"])
                    for s in manifest["sources"])
    source_by_id = {s.source_id: s for s in sources}
    scope = ReviewScope(**case["scope"], revision=1,
                        basis_digest=fingerprint("DRAFT-PARSER-CHECK", case["source_basis"]))
    page_results, blocks, raw_outputs, layout_by_handle = [], [], {}, {}
    for source in manifest["sources"]:
        reader = PdfReader(BytesIO(actual[source["path"]]), strict=True)
        if reader.is_encrypted or not reader.pages or len(reader.pages) != source["page_count"]:
            raise InputError("UNEXPECTED_ENCRYPTION_OR_PAGE_COUNT")
        for number, page in enumerate(reader.pages, 1):
            candidates = [(handle, item) for handle, item in manifest["page_handles"].items()
                          if item["source_id"] == source["source_id"] and item["page"] == number]
            if len(candidates) != 1:
                raise InputError("PAGE_MAP_MISMATCH")
            handle, authored = candidates[0]
            reference = (PACK / authored["manuscript"]).read_text(encoding="utf-8")
            plain, layout = page.extract_text(), page.extract_text(extraction_mode="layout")
            expected_lines = nonblank_lines(reference)
            plain_matches = nonblank_lines(plain) == expected_lines
            layout_matches = nonblank_lines(layout) == expected_lines
            passed = bool(plain.strip()) and plain_matches and layout_matches
            prefix = f"{source['source_id']}/page-{number}"
            raw_outputs[prefix + ".plain.txt"] = plain
            raw_outputs[prefix + ".layout.txt"] = layout
            layout_by_handle[handle] = layout
            page_results.append(dict(
                handle=handle, source_id=source["source_id"], source_version=source["version"], page=number,
                source_sha256=source["content_digest"], plain_sha256=digest(plain.encode()), layout_sha256=digest(layout.encode()),
                expected_nonblank_lines=len(expected_lines), parsed_nonblank_lines=len(nonblank_lines(plain)),
                full_plain_comparison=plain_matches, full_layout_comparison=layout_matches,
                status="PASS" if passed else "FAIL", plain_artifact=prefix + ".plain.txt",
                layout_artifact=prefix + ".layout.txt",
            ))
            # Real original parsed page inventory; no manuscript character offsets.
            blocks.append(OriginalBlock(
                handle, scope, source_by_id[source["source_id"]], number, 0, plain,
                dependencies=tuple(case["required_page_dependencies"].get(handle, ())),
                parser_verified=passed, fit_verified=False,
            ))
    if len(page_results) != manifest["page_count"]:
        raise InputError("COMBINED_PAGE_COUNT_MISMATCH")
    try:
        columns = revenue_columns(layout_by_handle["FIN-P1"])
        columns_pass = columns["values"] == {"2026": "4000000", "2027": "4400000"}
    except InputError as exc:
        columns, columns_pass = dict(reason=str(exc)), False
    fin1, fin2 = layout_by_handle["FIN-P1"], layout_by_handle["FIN-P2"]
    collateral = layout_by_handle["COLLATERAL-P1"]
    focus = dict(
        year_column_alignment=columns_pass,
        whole_usd_units="USD whole units; not thousands or millions." in fin1,
        annual_projection_context="2026 and 2027 columns below are supplied annual projections, not actuals." in fin1,
        cross_page_continuation="required scope qualification continue on FINANCIALS-1 page 2." in fin1,
        debt_service_qualification=("Qualification: Both payment lines include the proposed E-N01 loan and" in fin2
                                    and "remaining borrower funded debt after the documented repayment." in fin2),
        explicit_zero_liens=any(line.split() == ["Documented", "prior-ranking", "liens", "on", "this", "pool:", "0"]
                                for line in collateral.splitlines()),
    )
    coverage = {}
    for mode in ("BASELINE", "ADAPTIVE"):
        checked = verify_evidence(scope=scope, sources=sources, inventory=tuple(blocks), roots=(),
                                  selected=tuple(b.block_id for b in blocks), purpose="FULL_EXTRACTION",
                                  max_context_bytes=100000, mode=mode)
        coverage[mode] = dict(status=checked.status, reasons=checked.reasons,
                              context_bytes=checked.context_bytes, exposed_blocks=len(checked.dispatch_blocks))
    source_fit_withheld = all(c["status"] == "UNVERIFIED" and c["exposed_blocks"] == 0
                              and "SOURCE_FIT_UNVERIFIED" in c["reasons"] for c in coverage.values())
    passed = all(p["status"] == "PASS" for p in page_results) and all(focus.values()) and source_fit_withheld
    report = dict(
        evidence_type="APPLICATION_TEST", protocol="E-N01-PDF-COMPATIBILITY-1.0",
        status="PASS" if passed else "FAIL", parser="pypdf", parser_version=package.version,
        license_expression=package.metadata["License-Expression"],
        installed_license_sha256=digest(package.locate_file(license_file).read_bytes()),
        package_digest=manifest["package_digest"], source_files=len(sources), actual_page_count=len(page_results),
        comparison="Ordered nonblank lines; trailing whitespace ignored; interior spacing and all content preserved",
        page_results=page_results, focused_checks=focus, revenue_columns=columns, coverage=coverage,
        parsed_inventory=[dict(block_id=b.block_id, source_id=b.source.source_id, source_version=b.source.version,
                               source_sha256=b.source.content_digest, page=b.page, start=0, end=len(b.text),
                               dependencies=b.dependencies, parser_verified=b.parser_verified, source_fit_verified=False)
                          for b in blocks],
        source_fit_withheld=source_fit_withheld, case_approved=None, registered=None, registration_checked=False,
        human_supported=False, model_calls=0,
        limitations=["Known simple writer-generated PDFs only; not general upload acceptance",
                     "No PDF image rendering or measured glyph-box validation",
                     "Text fidelity is not source authority, semantic support or case approval",
                     "No full loan graph, model-quality, RAGAS or retrieval benchmark run"],
    )
    return report, raw_outputs


def main():
    try:
        report, texts = verify_pack()
    except InputError as exc:
        report, texts = dict(status="FAIL", evidence_type="APPLICATION_TEST", reason=str(exc)), {}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, text in texts.items():
        path = OUTPUT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    (OUTPUT / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: report[k] for k in ("status", "parser_version", "source_files", "actual_page_count",
                                          "focused_checks", "source_fit_withheld") if k in report}))
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
