"""Role-aware Human review panel; permissions and writes stay in services."""

from uuid import NAMESPACE_URL, uuid5
import sqlite3

from pydantic import ValidationError

from ..context import InputError, fingerprint
from ..review_actions import ACTION_LABELS, ReviewActionCommand, get_review_panel, record_review_action
from ..storage import OperationConflict, RunBusy, StaleRecord


STATUS_LABELS = {"AWAITING_REVIEW": "Awaiting human review", "NEEDS_INFORMATION": "Pending — additional information requested",
                 "APPROVED": "Approved — simulated UI decision", "REJECTED": "Rejected — simulated UI decision"}
REASONS = {"ROLE_READ_ONLY": "Your demo role has read-only access to these review actions.",
    "RUN_BUSY": "Another execution is active. Wait before recording a review action.",
    "APPROVER_TIER_REQUIRED": "Requires an Authorized Approver with the requested review tier.",
    "PREREQUISITE_UNSATISFIED": "Required evidence or specialist handling remains unresolved.",
    "INFORMATION_REQUEST_OUTSTANDING": "Additional information is outstanding; a comment cannot clear it.",
    "REVIEW_NOT_PENDING": "A final review decision has already been recorded.",
    "STALE_REVIEW": "This review is no longer pending or its reviewed basis has changed.",
    "EXACT_REVIEWED_DRAFT_REQUIRED": "The exact supported condition draft is required."}


def render_human_review(store, request_id, actor):
    import streamlit as st

    try:
        panel = get_review_panel(store, request_id, actor)
    except (InputError, OSError, sqlite3.Error):
        st.error("This review is unavailable for the selected role and deal.")
        return
    st.subheader("Human review")
    st.text(panel["title"])
    st.warning("Illustrative UI sample — no executed loan analysis. Actions record UI decisions only.")
    left, right = st.columns(2)
    status_slot = left.empty()
    status_slot.metric("Review status", STATUS_LABELS[panel["decision_status"]])
    right.metric("Report status", "Not generated by this preview")
    st.caption("AI recommendation: not evaluated in this preview. Reviewer identity and permissions are simulated.")
    request = panel["request"]
    st.text("Reviewer role: " + actor.persona + " · Required tier: " + request["required_tier"])
    for requirement in request["requirements"]:
        if not requirement["satisfied"]:
            st.error("Unresolved prerequisite: " + requirement["key"])
    if panel["information_pending"]:
        st.info("Requested information remains outstanding. Approval and rejection are unavailable in this preview until a real information-resolution workflow is connected.")
    displayed_key = "review_displayed_basis:" + request_id
    current = (panel["record_version"], request["gate_version"], request["analytical_basis_digest"])
    if displayed_key not in st.session_state:
        st.session_state[displayed_key] = current
    if st.button("Refresh review", key="review_refresh:" + request_id):
        st.session_state[displayed_key] = current
    displayed = st.session_state[displayed_key]
    stale = displayed != current
    if stale:
        st.warning("The review has changed since you opened it. Refresh review before taking another action. Your comments are retained.")
    actions = panel["actions"]
    permitted = [action for action, reason in actions.items() if reason is None]
    with st.expander("Action permissions"):
        for action, reason in actions.items():
            st.text(ACTION_LABELS[action] + ": " + ("Available" if reason is None else REASONS.get(reason, "Unavailable for this review.")))
    action_key = "review_action:" + request_id
    if st.session_state.get(action_key) not in permitted:
        st.session_state[action_key] = None
    action = st.selectbox("Review action", permitted, index=None, format_func=ACTION_LABELS.get,
                          key=action_key, placeholder="Choose an action", disabled=not permitted or stale)
    draft_key = "review_draft:" + request_id
    if draft_key not in st.session_state:
        st.session_state[draft_key] = {"comments": "", "information": ""}
    def remember(field, key):
        st.session_state[draft_key][field] = st.session_state[key]
    comment_key = "review_comments:" + request_id
    information_key = "review_information:" + request_id
    if comment_key not in st.session_state:
        st.session_state[comment_key] = st.session_state[draft_key]["comments"]
    # Ordinary widgets save session drafts on edit. Database writes require the
    # explicit button; switching deals never submits the previous deal's draft.
    with st.container(border=True):
        comments = st.text_area("Review comments (required)", max_chars=4096,
            key=comment_key, disabled=not permitted, on_change=remember, args=("comments", comment_key),
            help="Explain your decision or the information needed. Use synthetic information only.")
        requested = ""
        if action == "REQUEST_INFORMATION":
            if information_key not in st.session_state:
                st.session_state[information_key] = st.session_state[draft_key]["information"]
            requested = st.text_area("Requested information (required — one item per line)",
                max_chars=10240, key=information_key, on_change=remember, args=("information", information_key),
                help="List up to 20 distinct items. Each item can contain up to 512 characters.")
        submitted = st.button("Record review action", key="review_submit:" + request_id, type="primary",
                              disabled=action is None or stale or not permitted)
    if submitted:
        try:
            if not comments.strip():
                raise InputError("REVIEW_COMMENT_REQUIRED")
            items = [line.strip() for line in requested.splitlines() if line.strip()]
            if action == "REQUEST_INFORMATION" and not items:
                raise InputError("REQUESTED_INFORMATION_REQUIRED")
            # Same displayed form/payload => same operation identity across duplicate clicks.
            operation = str(uuid5(NAMESPACE_URL, fingerprint("REVIEW_UI_SUBMIT", dict(
                request_id=request_id, displayed=displayed, role=actor.persona,
                tiers=sorted(actor.allowed_review_tiers), action=action, comments=comments, items=items))))
            command = ReviewActionCommand(operation_id=operation, request_id=request_id,
                expected_version=displayed[0], expected_gate_version=displayed[1], expected_basis=displayed[2],
                action=action, comments=comments, requested_items=items)
            event = record_review_action(store, actor, command)
            st.success(ACTION_LABELS[event["action"]] + " recorded at " + event["timestamp_utc"]
                       + ". Refresh review before another action. No graph or report was completed.")
            panel = get_review_panel(store, request_id, actor)
            status_slot.metric("Review status", STATUS_LABELS[panel["decision_status"]])
        except ValidationError:
            st.error("Check the required comments and requested items. Items must be distinct, with no more than 20 items of 512 characters each.")
        except InputError as error:
            message = {"REVIEW_COMMENT_REQUIRED": "Review comments are required before recording an action.",
                       "REQUESTED_INFORMATION_REQUIRED": "List at least one item of requested information."}.get(str(error))
            st.error(message or "The action was not recorded. Check the current review permissions and prerequisites, then refresh. Your draft is retained.")
        except (OperationConflict, RunBusy, StaleRecord, OSError, sqlite3.Error):
            st.error("The action was not recorded. Check your role, comments, outstanding prerequisites and current review version, then refresh. Your draft is retained.")
    with st.expander("Review history", expanded=True):
        if not panel["history"]:
            st.info("No review comments or actions have been recorded.")
        for event in panel["history"]:
            st.text(event["timestamp_utc"] + " · " + event["reviewer_role"] + " (simulated)")
            st.text(ACTION_LABELS[event["action"]] + " · " + STATUS_LABELS[event["decision_status"]])
            st.caption("Reviewer ID: " + event["reviewer_id"])
            st.text(event["comments"])
            for item in event["requested_items"]:
                st.text("Requested: " + item)
            st.divider()
    st.caption("History is saved on this computer. It is not a tamper-proof audit system.")
